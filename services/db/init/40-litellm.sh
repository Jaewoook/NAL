#!/bin/bash
set -euo pipefail

: "${LITELLM_DB_USER:?LITELLM_DB_USER is required}"
: "${LITELLM_DB_PASS:?LITELLM_DB_PASS is required}"
: "${LITELLM_DB_NAME:?LITELLM_DB_NAME is required}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER "${LITELLM_DB_USER}" WITH PASSWORD '${LITELLM_DB_PASS}';
    CREATE DATABASE "${LITELLM_DB_NAME}" OWNER "${LITELLM_DB_USER}";
EOSQL
